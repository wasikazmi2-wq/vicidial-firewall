#!/usr/bin/env bash
# Builds install.sh: one self-contained file = a small bootstrap + a base64 tar.gz of src/ and official/.
# The result works as "sudo bash install.sh ..." and as "curl -fsSL URL | sudo bash -s -- ...".
set -euo pipefail
cd "$(dirname "$0")"
ver=$(sed -n 's/^VF_VERSION="\(.*\)"/\1/p' src/installer.sh | head -1)
stamp=$(date -u +%Y-%m-%dT%H:%M:%SZ)
out=${1:-install.sh}
for f in src/installer.sh src/vicidial-firewall official/VB-firewall.pl official/dynportal/valid8.php; do [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }; done
bash -n src/installer.sh; bash -n src/vicidial-firewall
payload=$(tar --owner=0 --group=0 --numeric-owner -czf - src official | base64 | tr -d '\r' | fold -w 76)
{
	cat <<EOF
#!/usr/bin/env bash
# vicidial-firewall $ver - single-file installer, generated by build.sh on $stamp
#
# Installs the official ViciDial / ViciBox firewall (VB-firewall.pl + Dynamic Portal + firewalld layout).
#   sudo bash install.sh --help
#   sudo bash install.sh [options]
#   curl -fsSL https://.../install.sh | sudo bash -s -- [options]
#
# This file is a bootstrap followed by a base64 tar.gz of the project (src/ and official/).
# Source and provenance of the official components: see README.md and official/SOURCES.md in the payload.
set -euo pipefail
command -v tar >/dev/null 2>&1 && command -v base64 >/dev/null 2>&1 || { echo "tar and base64 are required" >&2; exit 1; }
VF_PAYLOAD_B64=\$(cat <<'__VF_PAYLOAD_END__'
EOF
	printf '%s\n' "$payload"
	cat <<'EOF'
__VF_PAYLOAD_END__
)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/vicidial-firewall.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
printf '%s\n' "$VF_PAYLOAD_B64" | base64 -d | tar -xzf - -C "$tmp"
unset VF_PAYLOAD_B64
rc=0
bash "$tmp/src/installer.sh" --payload-dir="$tmp" "$@" || rc=$?
exit "$rc"
EOF
} >"$out"
chmod +x "$out"
bash -n "$out"
printf 'built %s (%s, %s bytes)\n' "$out" "$ver" "$(wc -c <"$out")"
